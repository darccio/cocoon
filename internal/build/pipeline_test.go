type pipelineRunner struct {
	guest string
	fail  string
	wasm  []byte
}

func (r pipelineRunner) Run(_ context.Context, _, program string, args ...string) ([]byte, error) {
	if len(args) > 0 && args[0] == "--version" {
		return []byte(program + " version 133"), nil
	}
	switch program {
	case "rustup":
		if args[0] == "component" {
			return []byte("rust-src\nrust-std-wasm32-unknown-unknown\n"), nil
		}
		if args[2] == "rustc" {
			return []byte("rustc 1.97.0 (test)"), nil
		}
		if args[3] == "metadata" {
			if r.fail == "metadata" {
				return []byte("invalid JSON"), nil
			}
			return json.Marshal(map[string]any{"packages": []any{map[string]any{"dependencies": []any{map[string]string{"name": "cocoon-guest", "path": r.guest}}}}})
		}
		if r.fail == "cargo" {
			return nil, fmt.Errorf("cargo failure")
		}
		return nil, nil
	case "git":
		if slices.Contains(args, "diff") {
			if r.fail == "dirty" {
				return nil, fmt.Errorf("dirty source")
			}
			return nil, nil
		}
		if r.fail == "revision" {
			return []byte("wrong revision"), nil
		}
		return []byte("0123456789012345678901234567890123456789"), nil
	case "go":
		if slices.Contains(args, "-version") {
			return []byte("wasm2go v0.4.16"), nil
		}
		if r.fail == "translator" {
			return nil, fmt.Errorf("translator failure")
		}
		index := slices.Index(args, "-o")
		return nil, os.WriteFile(args[index+1], []byte("// Code generated by wasm2go. DO NOT EDIT.\npackage wasm\n"), 0o600) // #nosec G304 -- Write the controlled fake translator destination in this test's temporary project.
	case "wasm-opt", "wasm-metadce":
		index := slices.Index(args, "-o")
		data := r.wasm
		if r.fail == "verify" {
			data = []byte("invalid")
		}
		return nil, os.WriteFile(args[index+1], data, 0o600) // #nosec G304 -- Write the controlled fake tool destination in this test's temporary project.
	default:
		return nil, fmt.Errorf("unexpected command %s", program)
	}
}

func fakeSources(_ context.Context, _ *manifest.Manifest) (rust, facade []byte, err error) {
	return []byte("// Code generated by cocoon. DO NOT EDIT.\n// Rust\n"), []byte("// Code generated by cocoon. DO NOT EDIT.\npackage test\n"), nil
}

func makeProject(t *testing.T) (string, pipelineRunner) {
	t.Helper()
	directory := t.TempDir()
	for path, data := range map[string]string{"go.mod": "module test\n", "shim/src/lib.rs": "// authored\n", "shim/Cargo.lock": "locked", "guest/Cargo.toml": "guest"} {
		target := filepath.Join(directory, path)
		if err := os.MkdirAll(filepath.Dir(target), 0o750); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(target, []byte(data), 0o600); err != nil { // #nosec G304 -- Create only explicit fixtures below t.TempDir.
			t.Fatal(err)
		}
	}
	return directory, pipelineRunner{guest: filepath.Join(directory, "guest"), wasm: abiModule(t, "", 2)}
}

func TestPipelineDeterminismAndFailureRollback(t *testing.T) {
	t.Parallel()
	directory, runner := makeProject(t)
	p := pipeline{runner: runner, sources: fakeSources}
	first, err := p.run(t.Context(), directory, testManifest(t))
	if err != nil {
		t.Fatal(err)
	}
	second, err := p.run(t.Context(), directory, testManifest(t))
	if err != nil {
		t.Fatal(err)
	}
	firstData, err := json.Marshal(first)
	if err != nil {
		t.Fatal(err)
	}
	secondData, err := json.Marshal(second)
	if err != nil || !bytes.Equal(firstData, secondData) {
		t.Fatal("lock identities changed across identical builds")
	}
	rustPath := filepath.Join(directory, "shim", "src", "cocoon_gen.rs")
	original, err := os.ReadFile(rustPath) // #nosec G304 -- Read our temporary generated fixture.
	if err != nil {
		t.Fatal(err)
	}
	for _, failure := range []string{"cargo", "translator", "verify"} {
		runner.fail = failure
		p.runner = runner
		p.sources = func(_ context.Context, _ *manifest.Manifest) ([]byte, []byte, error) {
			return append(slices.Clone(original), "// changed\n"...), firstData, nil
		}
		if _, buildErr := p.run(t.Context(), directory, testManifest(t)); buildErr == nil {
			t.Fatalf("%s failure accepted", failure)
		}
		restored, readErr := os.ReadFile(rustPath) // #nosec G304 -- Read our temporary generated fixture.
		if readErr != nil || !bytes.Equal(restored, original) {
			t.Fatal("failed build left mismatched Rust glue")
		}
	}
	if len(first.Sources) != 1 || first.Sources[0].Name != "cocoon-guest" || len(first.Go) != 64 {
		t.Fatal("missing source or artifact provenance")
	}
	for path, expected := range map[string]string{
		"go/test/zz_contract_test.go":           first.Contracts,
		"go/test/zz_wazero_test.go":             first.Differential,
		"go/test/internal/wasm/zz_bulk_test.go": first.Bulk,
	} {
		data, readErr := os.ReadFile(filepath.Join(directory, path)) // #nosec G304 -- Read only generated fixtures below t.TempDir.
		if readErr != nil || expected != digest(data) {
			t.Fatalf("missing or untracked generated test %s: %v", path, readErr)
		}
	}
}

func TestSourceDigestAndMissingModule(t *testing.T) {
	t.Parallel()
	directory, _ := makeProject(t)
	first, err := sourceDigest(directory)
	if err != nil {
		t.Fatal(err)
	}
	if directoryErr := os.Mkdir(filepath.Join(directory, "target"), 0o750); directoryErr != nil {
		t.Fatal(directoryErr)
	}
	second, err := sourceDigest(directory)
	if err != nil || first != second {
		t.Fatal("build cache changed source hash")
	}
	if err := os.Symlink(filepath.Join(directory, "go.mod"), filepath.Join(directory, "link.rs")); err == nil {
		if _, hashErr := sourceDigest(directory); hashErr == nil {
			t.Fatal("source symlink accepted")
		}
	}
	if _, err := sourceDigest(filepath.Join(directory, "missing")); err == nil {
		t.Fatal("missing source accepted")
	}
	if _, err := FindModule(t.TempDir()); err == nil {
		t.Fatal("missing Go module accepted")
	}
}

func TestSourceIdentityFailures(t *testing.T) {
	t.Parallel()
	directory, runner := makeProject(t)
	m := testManifest(t)
	m.Sources = []manifest.SourcePin{{Name: "upstream", Path: "guest", Revision: "0123456789012345678901234567890123456789"}}
	identities, paths, err := sourceIdentities(t.Context(), runner, directory, m)
	if err != nil || len(identities) != 2 {
		t.Fatal(err)
	}
	if len(paths) != 2 {
		t.Fatal("missing source path remaps")
	}
	for _, failure := range []string{"revision", "dirty", "metadata"} {
		runner.fail = failure
		if _, _, identityErr := sourceIdentities(t.Context(), runner, directory, m); identityErr == nil {
			t.Fatalf("accepted %s", failure)
		}
	}
	runner.fail = ""
	runner.guest = ""
	if _, _, identityErr := sourceIdentities(t.Context(), runner, directory, m); identityErr == nil {
		t.Fatal("accepted missing guest crate")
	}
}

func TestPipelinePreservesAuthoredOutputs(t *testing.T) {
	t.Parallel()
	directory, runner := makeProject(t)
	path := filepath.Join(directory, "go", "test", "cocoon_gen.go")
	if err := os.MkdirAll(filepath.Dir(path), 0o750); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(path, []byte("authored"), 0o600); err != nil {
		t.Fatal(err)
	}
	p := pipeline{runner: runner, sources: fakeSources}
	if _, err := p.run(t.Context(), directory, testManifest(t)); err == nil {
		t.Fatal("authored facade overwritten")
	}
	if _, err := os.Stat(filepath.Join(directory, "shim", "src", "cocoon_gen.rs")); !os.IsNotExist(err) {
		t.Fatal("failed first build left generated Rust glue")
	}
	if err := os.WriteFile(filepath.Join(directory, ".cocoon-build", "lock"), nil, 0o600); err != nil {
		t.Fatal(err)
	}
	if _, err := p.run(t.Context(), directory, testManifest(t)); err == nil {
		t.Fatal("concurrent or stale build lock ignored")
	}
}

func TestPipelinePreflightAndLateFailuresReleaseGuard(t *testing.T) {
	t.Parallel()
	for _, failure := range []string{"manifest", "source-identity", "source-generation", "cargo-lock"} {
		t.Run(failure, func(t *testing.T) {
			t.Parallel()
			directory, runner := makeProject(t)
			m := testManifest(t)
			p := pipeline{runner: runner, sources: fakeSources}
			switch failure {
			case "manifest":
				m.Package.Name = "../invalid"
			case "source-identity":
				runner.fail = "metadata"
				p.runner = runner
			case "source-generation":
				p.sources = func(context.Context, *manifest.Manifest) ([]byte, []byte, error) {
					return nil, nil, fmt.Errorf("source formatting failed")
				}
			case "cargo-lock":
				if err := os.Remove(filepath.Join(directory, "shim", "Cargo.lock")); err != nil {
					t.Fatal(err)
				}
			}
			if _, err := p.run(t.Context(), directory, m); err == nil {
				t.Fatalf("accepted %s failure", failure)
			}
			for _, path := range []string{".cocoon-build/lock", "shim/src/cocoon_gen.rs", "go/test/cocoon_gen.go", "cocoon.lock.json"} {
				if _, err := os.Stat(filepath.Join(directory, path)); !os.IsNotExist(err) {
					t.Fatalf("failed build left %s: %v", path, err)
				}
			}
			// A repaired build must work without manually removing a stale guard.
			if err := os.WriteFile(filepath.Join(directory, "shim", "Cargo.lock"), []byte("locked"), 0o600); err != nil {
				t.Fatal(err)
			}
			p = pipeline{runner: pipelineRunner{guest: runner.guest, wasm: runner.wasm}, sources: fakeSources}
			if _, err := p.run(t.Context(), directory, testManifest(t)); err != nil {
				t.Fatal("failed build prevented retry", err)
			}
		})
	}
}
