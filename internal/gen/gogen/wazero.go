package gogen

import (
	"fmt"
	"go/format"
	"strings"
	"text/template"

	"github.com/darccio/cocoon/internal/manifest"
)

type differentialOperation struct {
	name   string
	params []manifest.Param
}

// WazeroTests generates raw-ABI differential tests over the exact translated Wasm.
// The reference engine is imported only from generated test files.
func WazeroTests(m *manifest.Manifest) ([]byte, error) {
	if err := m.Validate(); err != nil {
		return nil, err
	}
	var operations []differentialOperation
	for _, function := range m.Functions {
		operations = append(operations, differentialOperation{name: "cocoon_" + function.Name, params: function.Params})
	}
	for _, resource := range m.Resources {
		for _, method := range resource.Methods {
			params := method.Params
			if method.Name != "new" {
				params = append([]manifest.Param{{Name: "handle", Type: "u64"}}, params...)
			}
			operations = append(operations, differentialOperation{name: "cocoon_" + strings.ToLower(resource.Name) + "_" + method.Name, params: params})
		}
	}
	var b strings.Builder
	tmpl, err := template.New("wazero").Delims("<<", ">>").Parse(differentialTemplate)
	if err != nil {
		return nil, err
	}
	if executionErr := tmpl.Execute(&b, m.Package.Name); executionErr != nil {
		return nil, executionErr
	}
	input, output, _, err := m.ByteLimits()
	if err != nil {
		return nil, err
	}
	fmt.Fprintf(&b, "const generatedInputLimit uint64=%d\nconst generatedOutputLimit uint64=%d\n", input, output)
	b.WriteString("func generatedInvoke(g *guest,name string,args []cocoontest.Arg,pointers []uint32) rt.Status {switch name {\n")
	for _, operation := range operations {
		var arguments []string
		for index, param := range operation.params {
			value := fmt.Sprintf("args[%d].Value", index)
			if m.Variable(param.Type) {
				arguments = append(arguments, fmt.Sprintf("int32(pointers[%d])", index), fmt.Sprintf("int32(len(args[%d].Bytes))", index))
				continue
			}
			switch param.Type {
			case "i32", "u32", "bool":
				value = "int32(" + value + ")"
			case "i64", "u64":
				value = "int64(" + value + ")"
			case "f32":
				value = "math.Float32frombits(uint32(" + value + "))"
			case "f64":
				value = "math.Float64frombits(" + value + ")"
			}
			arguments = append(arguments, value)
		}
		fmt.Fprintf(&b, "case %q:return rt.Status(g.module.X%s(%s))\n", operation.name, operation.name, strings.Join(arguments, ","))
	}
	b.WriteString("default:panic(\"unknown generated operation\")}}\n")
	b.WriteString("func generatedCases(t testing.TB) []generatedCase {t.Helper();return []generatedCase{\n")
	for _, operation := range operations {
		fmt.Fprintf(&b, "{name:%q,args:[]cocoontest.Arg{", operation.name)
		for _, param := range operation.params {
			if m.Variable(param.Type) {
				fmt.Fprintf(&b, "{Buffer:true,Bytes:generatedSeed(t,encode%s,%s)},", helperName(param.Type), zero(param.Type))
			} else {
				b.WriteString("{},")
			}
		}
		b.WriteString("}},\n")
	}
	b.WriteString("}}\n")
	// The blank reference keeps the stable test template usable for scalar-only APIs.
	b.WriteString("var _ = math.Float64bits\n")
	formatted, err := format.Source([]byte(b.String()))
	if err != nil {
		return nil, fmt.Errorf("format differential tests: %w", err)
	}
	return formatted, nil
}

// Keep the comparison algorithm identical for every generated API.
const differentialTemplate = `// Code generated by cocoon. DO NOT EDIT.
package <<.>>
import("bytes";_ "embed";"errors";"math";"testing";"github.com/darccio/cocoon/cocoontest";"github.com/darccio/cocoon/rt")
//go:embed testdata/module.wasm
var generatedWasm []byte
type generatedCase struct {name string;args []cocoontest.Arg}
func newDifferential(t testing.TB)(*guest,*cocoontest.Guest){
 t.Helper(); l,err:=Open(Options{Instances:1});if err!=nil{t.Fatal(err)};
 t.Cleanup(func(){if err:=l.Close();err!=nil{t.Error(err)}});
 g,err:=l.newGuest();if err!=nil{t.Fatal(err)};t.Cleanup(g.close);
 reference:=cocoontest.New(t,generatedWasm);
 for _,identity:=range []struct{name string;want uint64}{{"cocoon_abi_version",rt.ABIVersion},{"cocoon_schema_hash",schemaHash}}{
  got,err:=reference.Call(t.Context(),identity.name);if err!=nil||len(got)!=1||got[0]!=identity.want{t.Fatalf("reference identity %s: %v %v",identity.name,got,err)}
 }
 if _,err:=reference.Call(t.Context(),"cocoon_init");err!=nil{t.Fatal(err)};
 return g,reference
}
func compareOperation(t testing.TB,g *guest,reference *cocoontest.Guest,name string,args []cocoontest.Arg)(rt.Status,[]byte){
 t.Helper();var status rt.Status;var output []byte;
 err:=g.instance.Call(name,func(call *rt.Call)error{
  var size uint64;for _,arg:=range args {if arg.Buffer {next,err:=rt.InputSize(g.instanceLimits().MaxInput,1,size,uint64(len(arg.Bytes)));if err!=nil{return err};size=next}}
  if err:=call.PrepareInput(size);err!=nil{return err};pointers:=make([]uint32,len(args));
  for index,arg:=range args {if arg.Buffer {pointer,err:=call.PutBytes(arg.Bytes);if err!=nil{return err};pointers[index]=pointer}}
  status=generatedInvoke(g,name,args,pointers);var resultErr error;output,resultErr=call.Result(name,status);return resultErr
 });
 limits:=g.instanceLimits();referenceStatus,referenceOutput,referenceErr:=reference.Operation(t.Context(),name,args,limits.MaxInput,limits.MaxOutput);
 var fault *rt.FaultError;
 if errors.As(err,&fault){if referenceErr==nil{t.Fatalf("translated trap without reference trap: %v",err)};return status,nil}
 if referenceErr==nil{referenceErr=rt.FromStatus(name,referenceStatus,referenceOutput)}
 if (err==nil)!=(referenceErr==nil){t.Fatalf("%s error mismatch: Go=%v reference=%v",name,err,referenceErr)}
 if err!=nil{if err.Error()!=referenceErr.Error(){t.Fatalf("%s errors differ: Go=%v reference=%v",name,err,referenceErr)};return status,nil}
 if status!=referenceStatus||!bytes.Equal(output,referenceOutput){t.Fatalf("%s differs: Go=(%d,%x) reference=(%d,%x)",name,status,output,referenceStatus,referenceOutput)}
 return status,output
}
func(g *guest)instanceLimits()rt.Limits{return rt.Limits{MaxInput:generatedInputLimit,MaxOutput:generatedOutputLimit,MaxMemory:maximumMemory}}
func generatedSeed[T any](t testing.TB,encode func(T,uint64)([]byte,error),value T)[]byte{t.Helper();data,err:=encode(value,generatedInputLimit);if err!=nil{t.Fatal(err)};return data}
func TestGeneratedDifferential(t *testing.T){t.Parallel();for _,test:=range generatedCases(t){t.Run(test.name,func(t *testing.T){g,reference:=newDifferential(t);compareOperation(t,g,reference,test.name,test.args)})}}
func FuzzGeneratedDifferential(f *testing.F){f.Add(uint8(0),uint64(0),[]byte{});f.Add(uint8(0),uint64(1),[]byte{255,0,1});f.Fuzz(func(t *testing.T,selector uint8,scalar uint64,data []byte){
 if len(data)>4096{t.Skip()};cases:=generatedCases(t);if len(cases)==0{t.Skip()};test:=cases[int(selector)%len(cases)];
 bufferSet,scalarSet:=false,false;for index:=range test.args{arg:=&test.args[index];if arg.Buffer&&!bufferSet{arg.Bytes=data;bufferSet=true}else if !arg.Buffer&&!scalarSet{arg.Value=scalar;scalarSet=true}}
 g,reference:=newDifferential(t);compareOperation(t,g,reference,test.name,test.args)
})}
`
