// Contracts generates ownership, limits, and terminal-close regression tests.
func Contracts(m *manifest.Manifest) ([]byte, error) {
	if err := m.Validate(); err != nil {
		return nil, err
	}
	input, output, _, err := m.ByteLimits()
	if err != nil {
		return nil, err
	}
	var b strings.Builder
	fmt.Fprintf(&b, "// Code generated by cocoon. DO NOT EDIT.\npackage %s\nimport(\"testing\";\"errors\";\"github.com/darccio/cocoon/rt\"", m.Package.Name)
	if len(m.Resources) != 0 {
		b.WriteString(";\"reflect\";\"runtime\"")
	}
	b.WriteString(")\nfunc TestGeneratedLimitsAndClose(t *testing.T){t.Parallel();")
	fmt.Fprintf(&b, "for _,options:=range []Options{{MaxInput:%d},{MaxOutput:%d},{Instances:-1}} {if _,err:=Open(options);!errors.Is(err,rt.ErrTooLarge){t.Fatalf(\"invalid options: %%v\",err)}};", input+1, output+1)
	b.WriteString("l,err:=Open(Options{Instances:1});if err!=nil{t.Fatal(err)};if err:=l.Close();err!=nil{t.Fatal(err)};if err:=l.Close();err!=nil{t.Fatal(err)};\n")
	for _, function := range m.Functions {
		b.WriteString("{ ")
		if function.Returns != "" {
			b.WriteString("_,")
		}
		fmt.Fprintf(&b, "err:=l.%s(t.Context()%s);if !errors.Is(err,rt.ErrClosed){t.Fatalf(\"call after close: %%v\",err)} }\n", manifest.GoName(function.Name), zeroArguments(function.Params, true))
	}
	for _, resource := range m.Resources {
		constructor := resource.Methods[0]
		for _, method := range resource.Methods {
			if method.Name == "new" {
				constructor = method
			}
		}
		fmt.Fprintf(&b, "{ _,err:=l.New%s(%s);if !errors.Is(err,rt.ErrClosed){t.Fatalf(\"constructor after close: %%v\",err)} }\n", resource.Name, zeroArguments(constructor.Params, false))
	}
	b.WriteString("}\n")
	for _, resource := range m.Resources {
		var constructor manifest.Function
		for _, method := range resource.Methods {
			if method.Name == "new" {
				constructor = method
			}
		}
		arguments := zeroArguments(constructor.Params, false)
		fmt.Fprintf(&b, "func TestGenerated%sOwnership(t *testing.T){ t.Parallel(); l,err:=Open(Options{Instances:1});if err!=nil{t.Fatal(err)};t.Cleanup(func(){if err:=l.Close();err!=nil{t.Error(err)}}); r,err:=l.New%s(%s);", resource.Name, resource.Name, arguments)
		if constructor.Fallible {
			b.WriteString("if err!=nil { t.Skipf(\"constructor requires a domain-specific seed: %v\",err) };")
		} else {
			b.WriteString("if err!=nil {t.Fatal(err)};")
		}
		fmt.Fprintf(&b, "copyValue:=reflect.New(reflect.TypeOf(r).Elem());copyValue.Elem().Set(reflect.ValueOf(r).Elem());alias,ok:=copyValue.Interface().(*%s);if !ok{t.Fatal(\"wrapper copy\")};r=nil;runtime.GC();runtime.Gosched();if err:=alias.owner.Use(\"copy\",func(*rt.Instance,uint64)error{return nil});err!=nil{t.Fatal(err)};if err:=alias.Close();err!=nil{t.Fatal(err)};if err:=alias.Close();err!=nil{t.Fatal(err)};", resource.Name)
		b.WriteString("var handleErr *rt.HandleError;if err:=alias.owner.Use(\"closed\",func(*rt.Instance,uint64)error{t.Fatal(\"closed alias executed\");return nil});!errors.As(err,&handleErr){t.Fatalf(\"closed alias: %v\",err)};")
		fmt.Fprintf(&b, "faulted,err:=l.New%s(%s);if err!=nil{t.Fatal(err)};faultErr:=faulted.guest.instance.Call(\"fault\",func(*rt.Call)error{panic(\"integer overflow\")});var fault *rt.FaultError;if !errors.As(faultErr,&fault){t.Fatal(faultErr)};if err:=faulted.owner.Use(\"faulted\",func(*rt.Instance,uint64)error{t.Fatal(\"faulted resource executed\");return nil});!errors.As(err,&handleErr){t.Fatal(err)};", resource.Name, arguments)
		fmt.Fprintf(&b, "replacement,err:=l.New%s(%s);if err!=nil{t.Fatal(err)};if err:=replacement.owner.Use(\"replacement\",func(*rt.Instance,uint64)error{return nil});err!=nil{t.Fatal(err)};if err:=faulted.Close();err!=nil&&!errors.Is(err,rt.ErrClosed)&&!errors.Is(err,rt.ErrPoisoned){t.Fatal(err)};if err:=l.Close();err!=nil{t.Fatal(err)};if err:=replacement.owner.Use(\"library closed\",func(*rt.Instance,uint64)error{t.Fatal(\"released resource executed\");return nil});!errors.As(err,&handleErr){t.Fatal(err)} }\n", resource.Name, arguments)
	}
	return format.Source([]byte(b.String()))
}

func zeroArguments(params []manifest.Param, leading bool) string {
	var values []string
	for _, param := range params {
		values = append(values, zero(param.Type))
	}
	result := strings.Join(values, ",")
	if leading && result != "" {
		result = "," + result
	}
	return result
}

// BulkTests generates spare-capacity regression tests for exactly the emitted helpers.
func BulkTests(helpers []string) ([]byte, error) {
	var b strings.Builder
	b.WriteString("// Code generated by cocoon. DO NOT EDIT.\npackage wasm\nimport \"testing\"\nfunc TestGeneratedBulkMemoryBounds(t *testing.T){t.Parallel();\n")
	if len(helpers) != 0 {
		b.WriteString("memory:=make([]byte,1,8); tests:=[]func(){\n")
		for _, helper := range helpers {
			switch helper {
			case "memory_init":
				b.WriteString("func(){memory_init(memory,\"abc\",uint32(1),uint32(0),uint32(1))},func(){memory_init(memory,\"abc\",uint32(0),uint32(4),uint32(0))},\n")
			case "memory_copy":
				b.WriteString("func(){memory_copy(memory,uint32(1),uint32(0),uint32(1))},func(){memory_copy(memory,uint32(0),uint32(2),uint32(0))},\n")
			case "memory_fill":
				b.WriteString("func(){memory_fill(memory,uint32(1),int32(1),uint32(1))},func(){memory_fill(memory,uint32(2),int32(1),uint32(0))},\n")
			case "memory_zero":
				b.WriteString("func(){memory_zero(memory,uint32(1),uint32(1))},func(){memory_zero(memory,uint32(2),uint32(0))},\n")
			default:
				return nil, fmt.Errorf("unknown bulk-memory test helper %q", helper)
			}
		}
		b.WriteString("};for _,test:=range tests{func(){defer func(){if recover()==nil{t.Error(\"operation crossed logical memory length\")}}();test()}()}\n")
	}
	b.WriteString("}\n")
	return format.Source([]byte(b.String()))
}
