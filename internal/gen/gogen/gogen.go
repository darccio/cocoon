// Package gogen generates typed Go facades and adapters over translated guests.
package gogen

import (
	"fmt"
	"go/format"
	"strconv"
	"strings"

	"cocoon.dev/cocoon/internal/manifest"
)

// Facade emits bounded typed operations, pointer resources, and terminal lifecycle.
func Facade(m *manifest.Manifest) ([]byte, error) {
	if err := m.Validate(); err != nil {
		return nil, err
	}
	schema, _, err := m.SchemaHash()
	if err != nil {
		return nil, err
	}
	input, output, memory, err := m.ByteLimits()
	if err != nil {
		return nil, err
	}
	var b strings.Builder
	fmt.Fprintf(&b, "// Code generated by cocoon. DO NOT EDIT.\npackage %s\n", m.Package.Name)
	b.WriteString("import (\"context\";\"encoding/binary\";\"math\";\"log/slog\";\"runtime\";\"sync\";\"unicode/utf8\";\"cocoon.dev/cocoon/rt\")\n")
	fmt.Fprintf(&b, "const schemaHash uint64 = %d\nconst maximumMemory uint64 = %d\n", schema, memory)
	b.WriteString("type Options struct { Logger *slog.Logger; MaxInput,MaxOutput uint64; Instances int }\n")
	b.WriteString("type guest struct { module *module; instance *rt.Instance }\nfunc (g *guest) close() { g.instance.Close(); g.module=nil }\n")
	b.WriteString("type Library struct { pool *rt.Pool[guest]; home *guest; options Options; homeMu sync.Mutex; life rt.Lifecycle }\n")
	fmt.Fprintf(&b, "func Open(options Options) (*Library,error) { if options.MaxInput==0 { options.MaxInput=%d }; if options.MaxOutput==0 { options.MaxOutput=%d }; if options.MaxInput>%d || options.MaxOutput>%d || options.Instances<0 { return nil,rt.ErrTooLarge }; if options.Instances==0 { options.Instances=runtime.GOMAXPROCS(0);", input, output, input, output)
	if m.Limits.Instances != "gomaxprocs" {
		fmt.Fprintf(&b, "options.Instances=%s;", m.Limits.Instances)
	}
	b.WriteString("}; l:=&Library{options:options}; pool,err:=rt.NewPool(options.Instances,l.newGuest,func(g *guest) bool { return g.instance.Recycle(65536,maximumMemory) },func(g *guest){ g.close() }); if err!=nil { return nil,err }; l.pool=pool; return l,nil }\n")
	b.WriteString("func (l *Library) newGuest() (_guest *guest, _err error) { defer func(){ if value:=recover(); value!=nil { _err=rt.Classify(\"construct\",value,\"\") } }(); raw,host:=newModule(l.options); instance,err:=rt.NewInstance(raw,schemaHash,rt.Limits{MaxInput:l.options.MaxInput,MaxOutput:l.options.MaxOutput,MaxMemory:maximumMemory},host); if err!=nil { return nil,err }; return &guest{module:raw,instance:instance},nil }\n")
	b.WriteString("func (l *Library) admission(ctx context.Context) error { if l==nil { return rt.ErrClosed }; if err:=ctx.Err(); err!=nil { return err }; return l.life.Enter() }\n")
	b.WriteString("func (l *Library) getHome() (*guest,error) { l.homeMu.Lock(); defer l.homeMu.Unlock(); if l.home!=nil && !l.home.instance.Healthy() { l.home.close(); l.home=nil }; if l.home==nil { home,err:=l.newGuest(); if err!=nil { return nil,err }; l.home=home }; return l.home,nil }\n")
	b.WriteString("func (l *Library) Close() error { if l==nil { return nil }; return l.life.Close(func() error { err:=l.pool.Close(); l.homeMu.Lock(); defer l.homeMu.Unlock(); if l.home!=nil { l.home.close(); l.home=nil }; return err }) }\n")
	codec(&b)
	for _, record := range m.Records {
		recordCodec(&b, record)
	}
	for _, function := range m.Functions {
		operation(&b, m, function, "")
	}
	for _, resource := range m.Resources {
		fmt.Fprintf(&b, "type %s struct { _ rt.NoCopy; library *Library; guest *guest; owner *rt.Resource[%s] }\n", resource.Name, resource.Name)
		for _, method := range resource.Methods {
			operation(&b, m, method, resource.Name)
		}
	}
	formatted, err := format.Source([]byte(b.String()))
	if err != nil {
		return nil, fmt.Errorf("format facade: %w", err)
	}
	return formatted, nil
}

// Adapter emits a constructor matching the imports actually surviving meta-DCE.
func Adapter(m *manifest.Manifest, hasImports bool) ([]byte, error) {
	var b strings.Builder
	fmt.Fprintf(&b, "// Code generated by cocoon. DO NOT EDIT.\npackage %s\nimport (\"cocoon.dev/cocoon/rt\"; wasm %q)\n", m.Package.Name, m.Package.GoImport+"/internal/wasm")
	b.WriteString("type module struct { *wasm.Module }\nfunc(m *module) Memory() []byte { return *m.Xmemory().Slice() }\nfunc(m *module) Version() uint32 { return uint32(m.Xcocoon_abi_version()) }\nfunc(m *module) Schema() uint64 { return uint64(m.Xcocoon_schema_hash()) }\nfunc(m *module) Init() { m.Xcocoon_init() }\nfunc(m *module) Reserve(size uint32) uint32 { return uint32(m.Xcocoon_in_reserve(int32(size))) }\nfunc(m *module) Output() uint32 { return uint32(m.Xcocoon_out()) }\nfunc(m *module) Trim(keep uint32) { m.Xcocoon_trim(int32(keep)) }\n")
	b.WriteString("type imports struct { host *rt.Host }\n")
	if m.Capabilities.Log {
		b.WriteString("func(h imports) Xlog(level,pointer,size int32) { h.host.Log(level,uint32(pointer),uint32(size)) }\n")
	}
	if m.Capabilities.Random {
		b.WriteString("func(h imports) Xrandom_get(pointer,size int32) int32 { return h.host.RandomGet(uint32(pointer),uint32(size)) }\n")
	}
	if m.Capabilities.Clock {
		b.WriteString("func(h imports) Xclock_nanos() int64 { return h.host.ClockNanos() }\n")
	}
	b.WriteString("func newModule(options Options) (*module,*rt.Host) { host:=rt.NewHost(options.Logger); raw:=wasm.New(")
	if hasImports {
		b.WriteString("imports{host:host}")
	}
	b.WriteString("); adapter:=&module{Module:raw}; host.Bind(adapter); return adapter,host }\n")
	return format.Source([]byte(b.String()))
}

func goType(name string) string {
	switch name {
	case "i32":
		return "int32"
	case "u32":
		return "uint32"
	case "i64":
		return "int64"
	case "u64":
		return "uint64"
	case "f32":
		return "float32"
	case "f64":
		return "float64"
	case "bytes":
		return "[]byte"
	}
	if strings.HasPrefix(name, "[]") {
		return "[]" + goType(strings.TrimPrefix(name, "[]"))
	}
	return name
}

func helperName(name string) string {
	if strings.HasPrefix(name, "[]") {
		return "Slice" + manifest.GoName(strings.TrimPrefix(name, "[]"))
	}
	return manifest.GoName(name)
}

func zero(name string) string {
	switch name {
	case "string":
		return "\"\""
	case "bytes":
		return "nil"
	case "bool":
		return "false"
	case "i32", "u32", "i64", "u64", "f32", "f64":
		return "0"
	}
	if strings.HasPrefix(name, "[]") {
		return "nil"
	}
	return name + "{}"
}

func operation(b *strings.Builder, m *manifest.Manifest, function manifest.Function, resource string) {
	constructor := resource != "" && function.Name == "new"
	destructor := resource != "" && function.Name == "close"
	result := function.Returns
	var signature string
	switch {
	case resource == "":
		signature = "func(l *Library) " + manifest.GoName(function.Name) + "(_ctx context.Context"
	case constructor:
		signature = "func(l *Library) New" + resource + "("
	default:
		signature = "func(r *" + resource + ") " + manifest.GoName(function.Name) + "("
	}
	for index, param := range function.Params {
		if resource == "" || index > 0 {
			signature += ","
		}
		signature += "_arg" + strconv.Itoa(index) + " " + goType(param.Type)
	}
	signature += ") "
	if result != "" {
		resultType := goType(result)
		if constructor {
			resultType = "*" + resource
		}
		signature += "(" + resultType + ",error)"
	} else {
		signature += "error"
	}
	b.WriteString(signature + " {\n")
	failure := func(err string) string {
		if result == "" {
			return "return " + err
		}
		value := zero(result)
		if constructor {
			value = "nil"
		}
		return "return " + value + "," + err
	}
	if resource != "" && !constructor {
		fmt.Fprintf(b, "if r==nil || r.library==nil || r.owner==nil { %s };\n", failure("&rt.HandleError{Op:"+strconv.Quote(function.Name)+",Reason:\"nil resource\"}"))
		if destructor {
			b.WriteString("return r.owner.Close() }\n")
			return
		}
		b.WriteString("l:=r.library; _ctx:=context.Background();\n")
	} else if constructor {
		b.WriteString("_ctx:=context.Background();\n")
	}
	fmt.Fprintf(b, "if _err:=l.admission(_ctx); _err!=nil { %s }; defer l.life.Leave();\n", failure("_err"))
	hasBuffers := false
	for _, param := range function.Params {
		if m.Variable(param.Type) {
			hasBuffers = true
		}
	}
	if hasBuffers {
		b.WriteString("var _size uint64;\n")
	}
	b.WriteString("var _err error;\n")
	for index, param := range function.Params {
		if m.Variable(param.Type) {
			fmt.Fprintf(b, "_part%d,_err:=size%s(_arg%d,l.options.MaxInput); if _err!=nil { %s }; _size,_err=rt.InputSize(l.options.MaxInput,1,_size,_part%d); if _err!=nil { %s };\n", index, helperName(param.Type), index, failure("_err"), index, failure("_err"))
		}
	}
	for index, param := range function.Params {
		if m.Variable(param.Type) {
			if param.Type == "string" {
				fmt.Fprintf(b, "if !utf8.ValidString(_arg%d) { %s };\n", index, failure("&rt.AppError{Op:\"encode\",Status:rt.ErrArg,Message:\"invalid UTF-8\"}"))
				continue
			}
			fmt.Fprintf(b, "_data%d,_err:=encode%s(_arg%d,l.options.MaxInput); if _err!=nil { %s };\n", index, helperName(param.Type), index, failure("_err"))
		}
	}
	if result != "" {
		outputType := goType(result)
		if constructor {
			outputType = "uint64"
		}
		fmt.Fprintf(b, "var _output %s;\n", outputType)
	}
	if constructor {
		fmt.Fprintf(b, "_guest,_err:=l.getHome(); if _err!=nil { %s };\n", failure("_err"))
	}
	switch {
	case resource == "":
		b.WriteString("_err=l.pool.Do(_ctx,func(_guest *guest) error { return _guest.instance.Call(")
	case constructor:
		b.WriteString("_err=_guest.instance.Call(")
	default:
		fmt.Fprintf(b, "_err=r.owner.Use(%q,func(_instance *rt.Instance,_handle uint64) error { _guest:=r.guest; return _instance.Call(", function.Name)
	}
	fmt.Fprintf(b, "%q,func(_call *rt.Call) error {\n", function.Name)
	if hasBuffers {
		b.WriteString("if _inputErr:=_call.PrepareInput(_size); _inputErr!=nil { return _inputErr };\n")
	}
	var args []string
	if resource != "" && !constructor {
		args = append(args, "int64(_handle)")
	}
	for index, param := range function.Params {
		arg := "_arg" + strconv.Itoa(index)
		if m.Variable(param.Type) {
			data, put := fmt.Sprintf("_data%d", index), "PutBytes"
			if param.Type == "string" {
				data, put = arg, "PutString"
			}
			fmt.Fprintf(b, "_pointer%d,_putErr:=_call.%s(%s); if _putErr!=nil { return _putErr };\n", index, put, data)
			args = append(args, fmt.Sprintf("int32(_pointer%d)", index), "int32(len("+data+"))")
		} else {
			switch param.Type {
			case "bool":
				arg = "boolParam(" + arg + ")"
			case "u32":
				arg = "int32(" + arg + ")"
			case "u64":
				arg = "int64(" + arg + ")"
			}
			args = append(args, arg)
		}
	}
	export := function.Name
	if resource != "" {
		export = strings.ToLower(resource) + "_" + export
	}
	fmt.Fprintf(b, "_status:=rt.Status(_guest.module.Xcocoon_%s(%s)); _reply,_resultErr:=_call.Result(%q,_status); if _resultErr!=nil { return _resultErr };\n", export, strings.Join(args, ","), function.Name)
	if result == "" {
		b.WriteString("if len(_reply)!=0 { return rt.ErrProtocol }; return nil\n")
	} else {
		typ := result
		if constructor {
			typ = "u64"
		}
		fmt.Fprintf(b, "_decoded,_decodeErr:=decode%s(_reply,l.options.MaxOutput); if _decodeErr!=nil { return _decodeErr }; _output=_decoded; return nil\n", helperName(typ))
	}
	b.WriteString("})")
	if resource == "" || (resource != "" && !constructor) {
		b.WriteString(" })")
	}
	b.WriteString(";\n")
	switch {
	case constructor:
		fmt.Fprintf(b, "if _err!=nil { return nil,_err }; _owner,_ownErr:=rt.NewResource[%s](_guest.instance,_output,func(_handle uint64) error { return _guest.instance.Call(\"close\",func(_call *rt.Call) error { _status:=rt.Status(_guest.module.Xcocoon_%s_close(int64(_handle))); _,_closeErr:=_call.Result(\"close\",_status); return _closeErr }) }); if _ownErr!=nil { return nil,_ownErr }; return &%s{library:l,guest:_guest,owner:_owner},nil\n", resource, strings.ToLower(resource), resource)
	case result != "":
		b.WriteString("return _output,_err\n")
	default:
		b.WriteString("return _err\n")
	}
	b.WriteString("}\n")
}

func codec(b *strings.Builder) {
	b.WriteString("func boolParam(value bool) int32 { if value { return 1 }; return 0 }\n")
	b.WriteString("func sizeString(value string,limit uint64)(uint64,error){ return rt.InputSize(limit,uint64(len(value)),1) }\nfunc sizeBytes(value []byte,limit uint64)(uint64,error){ return rt.InputSize(limit,uint64(len(value)),1) }\n")
	b.WriteString("func encodeString(value string,limit uint64)([]byte,error){ if _,err:=sizeString(value,limit);err!=nil{return nil,err};if !utf8.ValidString(value){return nil,&rt.AppError{Status:rt.ErrArg,Op:\"encode\",Message:\"invalid UTF-8\"}};return []byte(value),nil }\nfunc encodeBytes(value []byte,limit uint64)([]byte,error){if _,err:=sizeBytes(value,limit);err!=nil{return nil,err};return value,nil}\n")
	b.WriteString("func decodeString(data []byte,limit uint64)(string,error){if uint64(len(data))>limit{return \"\",rt.ErrTooLarge};if !utf8.Valid(data){return \"\",rt.ErrProtocol};return string(data),nil}\nfunc decodeBytes(data []byte,limit uint64)([]byte,error){if uint64(len(data))>limit{return nil,rt.ErrTooLarge};return data,nil}\n")
	b.WriteString("func sizeBool(_ bool,limit uint64)(uint64,error){return rt.InputSize(limit,1,1)}\nfunc encodeBool(value bool,limit uint64)([]byte,error){if limit<1{return nil,rt.ErrTooLarge};return []byte{byte(boolParam(value))},nil}\nfunc decodeBool(data []byte,_ uint64)(bool,error){if len(data)!=1 || data[0]>1{return false,rt.ErrProtocol};return data[0]==1,nil}\n")
	for _, typ := range []string{"i32", "u32", "i64", "u64", "f32", "f64"} {
		goTyp := goType(typ)
		name := helperName(typ)
		width := 8
		bits := "64"
		if strings.HasSuffix(typ, "32") {
			width = 4
			bits = "32"
		}
		encoded := "uint" + bits + "(value)"
		decoded := goTyp + "(binary.LittleEndian.Uint" + bits + "(data))"
		if strings.HasPrefix(typ, "f") {
			encoded = "math.Float" + bits + "bits(value)"
			decoded = "math.Float" + bits + "frombits(binary.LittleEndian.Uint" + bits + "(data))"
		}
		fmt.Fprintf(b, "func size%s(_ %s,limit uint64)(uint64,error){return rt.InputSize(limit,1,%d)}\n", name, goTyp, width)
		fmt.Fprintf(b, "func encode%s(value %s,limit uint64)([]byte,error){if limit<%d{return nil,rt.ErrTooLarge};return binary.LittleEndian.AppendUint%s(nil,%s),nil}\n", name, goTyp, width, bits, encoded)
		fmt.Fprintf(b, "func decode%s(data []byte,_ uint64)(%s,error){if len(data)!=%d{return 0,rt.ErrProtocol};return %s,nil}\n", name, goTyp, width, decoded)
		fmt.Fprintf(b, "func sizeSlice%s(value []%s,limit uint64)(uint64,error){return rt.InputSize(limit,uint64(len(value)),%d)}\n", name, goTyp, width)
		fmt.Fprintf(b, "func encodeSlice%s(values []%s,limit uint64)([]byte,error){size,err:=sizeSlice%s(values,limit);if err!=nil{return nil,err};data:=make([]byte,0,int(size));for _,value:=range values{ data=binary.LittleEndian.AppendUint%s(data,%s) };return data,nil}\n", name, goTyp, name, bits, encoded)
		fmt.Fprintf(b, "func decodeSlice%s(data []byte,limit uint64)([]%s,error){if uint64(len(data))>limit{return nil,rt.ErrTooLarge};if len(data)%%%d!=0{return nil,rt.ErrProtocol};values:=make([]%s,len(data)/%d);for index:=range values { _part:=data[index*%d:]; values[index]=%s };return values,nil}\n", name, goTyp, width, goTyp, width, width, strings.ReplaceAll(decoded, "(data)", "(_part)"))
	}
}

func recordCodec(b *strings.Builder, record manifest.Record) {
	fmt.Fprintf(b, "type %s struct {\n", record.Name)
	for _, field := range record.Fields {
		fmt.Fprintf(b, "%s %s\n", manifest.GoName(field.Name), goType(field.Type))
	}
	b.WriteString("}\n")
	fmt.Fprintf(b, "func size%s(value %s,limit uint64)(uint64,error){total,err:=rt.InputSize(limit,%d,8,4);if err!=nil{return 0,err};\n", record.Name, record.Name, len(record.Fields))
	for index, field := range record.Fields {
		fmt.Fprintf(b, "part%d,err:=size%s(value.%s,limit);if err!=nil{return 0,err};total,err=rt.InputSize(limit,1,total,part%d);if err!=nil{return 0,err};\n", index, helperName(field.Type), manifest.GoName(field.Name), index)
	}
	b.WriteString("return total,nil}\n")
	fmt.Fprintf(b, "func encode%s(value %s,limit uint64)([]byte,error){if _,err:=size%s(value,limit);err!=nil{return nil,err};\n", record.Name, record.Name, record.Name)
	for index, field := range record.Fields {
		fmt.Fprintf(b, "part%d,err:=encode%s(value.%s,limit);if err!=nil{return nil,err};\n", index, helperName(field.Type), manifest.GoName(field.Name))
	}
	b.WriteString("return rt.EncodeRecord([]rt.Field{")
	for index := range record.Fields {
		fmt.Fprintf(b, "{ID:%d,Data:part%d},", index+1, index)
	}
	b.WriteString("},limit)}\n")
	fmt.Fprintf(b, "func decode%s(data []byte,limit uint64)(%s,error){var value %s;fields,err:=rt.DecodeRecord(data,%d,limit);if err!=nil{return value,err};\n", record.Name, record.Name, record.Name, len(record.Fields))
	for index, field := range record.Fields {
		fmt.Fprintf(b, "value.%s,err=decode%s(fields[%d],limit);if err!=nil{return value,err};\n", manifest.GoName(field.Name), helperName(field.Type), index)
	}
	b.WriteString("return value,nil}\n")
}
