package gen_test

import (
	"bytes"
	"os"
	"path/filepath"
	"testing"

	"github.com/darccio/cocoon/internal/gen"
)

func TestWriteGeneratedProtectsAuthoredFiles(t *testing.T) {
	t.Parallel()
	path := filepath.Join(t.TempDir(), "nested", "output.go")
	first := []byte("// Code generated by cocoon. DO NOT EDIT.\npackage first\n")
	if err := gen.WriteGenerated(path, first); err != nil {
		t.Fatal(err)
	}
	if err := gen.WriteGenerated(path, []byte("package authored\n")); err != nil {
		t.Fatal(err)
	}
	if err := gen.WriteGenerated(path, first); err == nil {
		t.Fatal("authored file overwritten")
	}
	link := filepath.Join(t.TempDir(), "link.go")
	if err := os.Symlink(path, link); err != nil {
		t.Skip(err)
	}
	if err := gen.WriteGenerated(link, first); err == nil {
		t.Fatal("symlink overwritten")
	}
}

func TestWriteSetPreflightsAllArtifacts(t *testing.T) {
	t.Parallel()
	directory := t.TempDir()
	first := filepath.Join(directory, "first.go")
	second := filepath.Join(directory, "second.go")
	original := []byte("// Code generated by cocoon. DO NOT EDIT.\npackage original\n")
	if err := gen.WriteGenerated(first, original); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(second, []byte("authored"), 0o600); err != nil {
		t.Fatal(err)
	}
	if err := gen.WriteSet([]gen.Artifact{{Path: first, Data: []byte("replacement"), Generated: true}, {Path: second, Data: original, Generated: true}}); err == nil {
		t.Fatal("authored artifact overwritten")
	}
	data, err := os.ReadFile(first) // #nosec G304 -- Read back this test's own temporary artifact.
	if err != nil || !bytes.Equal(data, original) {
		t.Fatal("earlier artifact changed after failed preflight")
	}
	if err := gen.WriteSet([]gen.Artifact{{Path: first, Data: original, Generated: true}, {Path: first, Data: original, Generated: true}}); err == nil {
		t.Fatal("duplicate destinations accepted")
	}
	link := filepath.Join(directory, "link")
	if err := os.Symlink(directory, link); err != nil {
		t.Skip(err)
	}
	if err := gen.WriteGenerated(filepath.Join(link, "escaped.go"), original); err == nil {
		t.Fatal("parent symlink accepted")
	}
}
