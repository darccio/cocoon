func TestWriteGeneratedProtectsAuthoredFiles(t *testing.T) {
	t.Parallel()
	path := filepath.Join(t.TempDir(), "nested", "output.go")
	first := []byte("// Code generated by cocoon. DO NOT EDIT.\npackage first\n")
	if err := gen.WriteGenerated(path, first); err != nil {
		t.Fatal(err)
	}
	if err := gen.WriteGenerated(path, []byte("package authored\n")); err != nil {
		t.Fatal(err)
	}
	if err := gen.WriteGenerated(path, first); err == nil {
		t.Fatal("authored file overwritten")
	}
	link := filepath.Join(t.TempDir(), "link.go")
	if err := os.Symlink(path, link); err != nil {
		t.Skip(err)
	}
	if err := gen.WriteGenerated(link, first); err == nil {
		t.Fatal("symlink overwritten")
	}
}

func TestWriteSetPreflightsAllArtifacts(t *testing.T) {
	t.Parallel()
	directory := t.TempDir()
	first := filepath.Join(directory, "first.go")
	second := filepath.Join(directory, "second.go")
	original := []byte("// Code generated by cocoon. DO NOT EDIT.\npackage original\n")
	if err := gen.WriteGenerated(first, original); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(second, []byte("authored"), 0o600); err != nil {
		t.Fatal(err)
	}
	if err := gen.WriteSet([]gen.Artifact{{Path: first, Data: []byte("replacement"), Generated: true}, {Path: second, Data: original, Generated: true}}); err == nil {
		t.Fatal("authored artifact overwritten")
	}
	data, err := os.ReadFile(first) // #nosec G304 -- Read back this test's own temporary artifact.
	if err != nil || !bytes.Equal(data, original) {
		t.Fatal("earlier artifact changed after failed preflight")
	}
	if err := gen.WriteSet([]gen.Artifact{{Path: first, Data: original, Generated: true}, {Path: first, Data: original, Generated: true}}); err == nil {
		t.Fatal("duplicate destinations accepted")
	}
	link := filepath.Join(directory, "link")
	if err := os.Symlink(directory, link); err != nil {
		t.Skip(err)
	}
	if err := gen.WriteGenerated(filepath.Join(link, "escaped.go"), original); err == nil {
		t.Fatal("parent symlink accepted")
	}
}

func TestWriteSetPreservesModesAndCleansStaging(t *testing.T) {
	t.Parallel()
	directory := t.TempDir()
	first := filepath.Join(directory, "first.go")
	original := []byte("// Code generated by cocoon. DO NOT EDIT.\npackage original\n")
	if err := os.WriteFile(first, original, 0o640); err != nil { // #nosec G306 -- Verify preservation of deliberately nondefault fixture permissions.
		t.Fatal(err)
	}
	if err := gen.WriteSet([]gen.Artifact{{Path: first, Data: original, Generated: true}, {Path: filepath.Join(directory, "second.go"), Data: original, Generated: true}}); err != nil {
		t.Fatal(err)
	}
	info, err := os.Stat(first)
	if err != nil || info.Mode().Perm() != 0o640 {
		t.Fatal("replacement changed original file permissions", err)
	}
	// A file in place of a later output directory must fail before publishing
	// any earlier staged replacement, without leaving backups behind.
	if writeErr := gen.WriteSet([]gen.Artifact{{Path: first, Data: []byte("replacement"), Generated: true}, {Path: filepath.Join(first, "blocked.go"), Data: original, Generated: true}}); writeErr == nil {
		t.Fatal("non-directory output parent accepted")
	}
	preserved, err := os.ReadFile(first) // #nosec G304 -- Read this test's own artifact below t.TempDir.
	if err != nil || !bytes.Equal(preserved, original) {
		t.Fatal("failed staging changed an earlier artifact", err)
	}
	entries, err := os.ReadDir(directory)
	if err != nil || len(entries) != 2 {
		t.Fatal("publication left temporary files", err)
	}
	if err := gen.WriteGenerated(directory, original); err == nil {
		t.Fatal("directory artifact accepted")
	}
}

func TestProjectRejectsInvalidManifestAndReleasesGuard(t *testing.T) {
	t.Parallel()
	directory := t.TempDir()
	if err := gen.Project(t.Context(), directory, &manifest.Manifest{}); err == nil {
		t.Fatal("invalid manifest accepted")
	}
	release, err := gen.Guard(directory)
	if err != nil {
		t.Fatal("failed generation stranded project guard", err)
	}
	if err := gen.Project(t.Context(), directory, &manifest.Manifest{}); err == nil {
		t.Fatal("concurrent generation admitted")
	}
	if err := release(); err != nil {
		t.Fatal(err)
	}
}

func TestProjectWithPinnedFormatter(t *testing.T) {
	t.Parallel()
	rustup, err := exec.LookPath("rustup")
	if err != nil {
		t.Skip("Rust formatter is needed only for generation integration")
	}
	probe := exec.CommandContext(t.Context(), rustup, "run", "1.97.0", "rustfmt", "--version") // #nosec G204 -- Invoke a resolved tool with fixed arguments.
	if probeErr := probe.Run(); probeErr != nil {
		t.Skip("pinned Rust formatter unavailable")
	}
	data, err := os.ReadFile("../../testdata/compute/cocoon.toml")
	if err != nil {
		t.Fatal(err)
	}
	m, err := manifest.Parse(data)
	if err != nil {
		t.Fatal(err)
	}
	directory := t.TempDir()
	if err := gen.Project(t.Context(), directory, m); err != nil {
		t.Fatal(err)
	}
	path := filepath.Join(directory, "go", m.Package.Name, "cocoon_gen.go")
	if err := os.WriteFile(path, []byte("authored"), 0o600); err != nil { // #nosec G703 -- The validated manifest selects a fixture below t.TempDir.
		t.Fatal(err)
	}
	if err := gen.Project(t.Context(), directory, m); err == nil {
		t.Fatal("authored facade overwritten")
	}
	ctx, cancel := context.WithCancel(t.Context())
	cancel()
	if _, _, err := gen.Sources(ctx, m); !errors.Is(err, context.Canceled) {
		t.Fatal("formatter cancellation ignored", err)
	}
}
