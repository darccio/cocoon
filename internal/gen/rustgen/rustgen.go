// Package rustgen generates safe traits and the ABI glue surrounding authored Rust.
package rustgen

import (
	"fmt"
	"strconv"
	"strings"

	"github.com/darccio/cocoon/internal/manifest"
)

// Generate emits a complete synchronous shim module for crate::Shim: API + Default.
func Generate(m *manifest.Manifest) ([]byte, error) {
	if err := m.Validate(); err != nil {
		return nil, err
	}
	schema, _, err := m.SchemaHash()
	if err != nil {
		return nil, err
	}
	input, output, _, err := m.ByteLimits()
	if err != nil {
		return nil, err
	}
	var b strings.Builder
	b.WriteString("// Code generated by cocoon. DO NOT EDIT.\n#![allow(unused_imports)]\nuse cocoon_guest::{Error, Result, Slab};\nuse std::cell::RefCell;\n")
	for _, record := range m.Records {
		fmt.Fprintf(&b, "#[derive(Debug, Clone, PartialEq)]\npub struct %s {\n", record.Name)
		for _, field := range record.Fields {
			fmt.Fprintf(&b, "pub %s: %s,\n", field.Name, rustType(field.Type))
		}
		b.WriteString("}\n")
		fmt.Fprintf(&b, "impl %s { pub fn decode(data: &[u8]) -> Result<Self> { let fields=cocoon_guest::decode_record(data,%d,%d)?; Ok(Self {\n", record.Name, len(record.Fields), input)
		for index, field := range record.Fields {
			fmt.Fprintf(&b, "%s: %s,\n", field.Name, decode(field.Type, fmt.Sprintf("fields[%d]", index)))
		}
		b.WriteString("}) }\n")
		fmt.Fprintf(&b, "pub fn encode(self) -> Result<Vec<u8>> { cocoon_guest::encode_record(&[\n")
		for _, field := range record.Fields {
			fmt.Fprintf(&b, "%s,\n", encode(field.Type, "self."+field.Name))
		}
		fmt.Fprintf(&b, "],%d) } }\n", output)
	}
	b.WriteString("#[allow(clippy::upper_case_acronyms)]\npub trait API {\n")
	for _, resource := range m.Resources {
		fmt.Fprintf(&b, "type %s;\n", resource.Name)
	}
	for _, function := range m.Functions {
		traitMethod(&b, function, "")
	}
	for _, resource := range m.Resources {
		for _, method := range resource.Methods {
			traitMethod(&b, method, resource.Name)
		}
	}
	b.WriteString("}\nstruct State { service: crate::Shim,\n")
	for _, resource := range m.Resources {
		fmt.Fprintf(&b, "%s: Slab<<crate::Shim as API>::%s>,\n", strings.ToLower(resource.Name), resource.Name)
	}
	b.WriteString("}\nthread_local! { static STATE: RefCell<State> = RefCell::new(State { service: Default::default(),\n")
	for _, resource := range m.Resources {
		fmt.Fprintf(&b, "%s: Slab::default(),\n", strings.ToLower(resource.Name))
	}
	b.WriteString("}); }\n")
	for _, export := range []struct{ name, parameters, returns, body string }{
		{"abi_version", "", "u32", "cocoon_guest::ABI_VERSION"},
		{"schema_hash", "", "u64", strconv.FormatUint(schema, 10) + "u64"},
		{"init", "", "()", fmt.Sprintf("cocoon_guest::init(%d,%d)", input, output)},
		{"in_reserve", "length: usize", "*mut u8", "cocoon_guest::reserve(length)"},
		{"out", "", "*const cocoon_guest::Output", "cocoon_guest::output()"},
		{"trim", "keep: usize", "()", "cocoon_guest::trim(keep)"},
		{"alloc", "length: usize", "*mut u8", "cocoon_guest::alloc(length)"},
	} {
		result := ""
		if export.returns != "()" {
			result = " -> " + export.returns
		}
		fmt.Fprintf(&b, "#[unsafe(no_mangle)] pub extern \"C\" fn cocoon_%s(%s)%s { %s }\n", export.name, export.parameters, result, export.body)
	}
	for _, function := range m.Functions {
		exportMethod(&b, m, function, "")
	}
	for _, resource := range m.Resources {
		for _, method := range resource.Methods {
			exportMethod(&b, m, method, resource.Name)
		}
	}
	return []byte(b.String()), nil
}

func rustType(name string) string {
	switch name {
	case "string":
		return "String"
	case "bytes":
		return "Vec<u8>"
	case "":
		return "()"
	}
	if strings.HasPrefix(name, "[]") {
		return "Vec<" + strings.TrimPrefix(name, "[]") + ">"
	}
	return name
}

func traitMethod(b *strings.Builder, function manifest.Function, resource string) {
	name := function.Name
	result := rustType(function.Returns)
	if resource != "" {
		name = strings.ToLower(resource) + "_" + name
		if function.Name == "new" {
			result = "Self::" + resource
		}
	}
	// The manifest deliberately permits wide typed APIs; keep the exemption local.
	if len(function.Params)+1 > 7 || (resource != "" && function.Name != "new" && len(function.Params)+2 > 7) {
		b.WriteString("#[allow(clippy::too_many_arguments)]\n")
	}
	fmt.Fprintf(b, "fn %s(&mut self", name)
	if resource != "" && function.Name != "new" {
		if function.Name == "close" {
			fmt.Fprintf(b, ", resource: Self::%s", resource)
		} else {
			fmt.Fprintf(b, ", resource: &mut Self::%s", resource)
		}
	}
	for index, param := range function.Params {
		fmt.Fprintf(b, ", arg%d: %s", index, rustType(param.Type))
	}
	if function.Fallible {
		result = "Result<" + result + ">"
	}
	b.WriteString(")")
	if result != "()" {
		fmt.Fprintf(b, " -> %s", result)
	}
	if function.Name == "close" && resource != "" {
		if function.Fallible {
			b.WriteString(" { drop(resource); Ok(()) }\n")
		} else {
			b.WriteString(" { drop(resource); }\n")
		}
	} else {
		b.WriteString(";\n")
	}
}

func exportMethod(b *strings.Builder, m *manifest.Manifest, function manifest.Function, resource string) {
	name := function.Name
	if resource != "" {
		name = strings.ToLower(resource) + "_" + name
	}
	fmt.Fprintf(b, "#[unsafe(no_mangle)] pub extern \"C\" fn cocoon_%s(", name)
	if resource != "" && function.Name != "new" {
		b.WriteString("__handle: u64,")
	}
	for index, param := range function.Params {
		argument := fmt.Sprintf("arg%d", index)
		switch {
		case m.Variable(param.Type):
			fmt.Fprintf(b, "%s_ptr: usize,%s_len: usize,", argument, argument)
		case param.Type == "bool":
			fmt.Fprintf(b, "%s: u32,", argument)
		default:
			fmt.Fprintf(b, "%s: %s,", argument, rustType(param.Type))
		}
	}
	replyType, replyFunction := "Vec<u8>", "reply"
	if function.Returns == "" {
		replyType, replyFunction = "()", "reply_unit"
	}
	fmt.Fprintf(b, ") -> i32 { let __result=STATE.with_borrow_mut(|__state| -> Result<%s> {\n", replyType)
	for index, param := range function.Params {
		argument := fmt.Sprintf("arg%d", index)
		if m.Variable(param.Type) {
			decoded := decode(param.Type, "__"+argument+".as_slice()")
			switch param.Type {
			case "bytes":
				decoded = "__" + argument
			case "string":
				decoded = "String::from_utf8(__" + argument + ").map_err(|_| Error::argument(\"invalid UTF-8\"))?"
			}
			fmt.Fprintf(b, "let __%s=cocoon_guest::input(%s_ptr,%s_len)?; let %s=%s;\n", argument, argument, argument, argument, decoded)
		} else if param.Type == "bool" {
			fmt.Fprintf(b, "let %s=match %s { 0=>false,1=>true,_=>return Err(Error::argument(\"invalid bool\")) };\n", argument, argument)
		}
	}
	var arguments []string
	if resource != "" && function.Name != "new" {
		field := strings.ToLower(resource)
		if function.Name == "close" {
			fmt.Fprintf(b, "let __resource=__state.%s.remove(__handle)?;\n", field)
		} else {
			fmt.Fprintf(b, "let __resource=__state.%s.get_mut(__handle)?;\n", field)
		}
		arguments = append(arguments, "__resource")
	}
	for index := range function.Params {
		arguments = append(arguments, fmt.Sprintf("arg%d", index))
	}
	suffix := ""
	if function.Fallible {
		suffix = "?"
	}
	if function.Returns != "" {
		b.WriteString("let __value=")
	}
	fmt.Fprintf(b, "__state.service.%s(%s)%s;\n", name, strings.Join(arguments, ","), suffix)
	switch {
	case resource != "" && function.Name == "new":
		fmt.Fprintf(b, "let __handle=__state.%s.insert(__value)?; Ok(__handle.to_le_bytes().to_vec())\n", strings.ToLower(resource))
	case function.Returns == "":
		b.WriteString("Ok(())\n")
	case m.Variable(function.Returns) && function.Returns != "string" && function.Returns != "bytes" && !strings.HasPrefix(function.Returns, "[]"):
		b.WriteString("__value.encode()\n")
	default:
		fmt.Fprintf(b, "Ok(%s)\n", encode(function.Returns, "__value"))
	}
	fmt.Fprintf(b, "}); cocoon_guest::%s(__result) }\n", replyFunction)
}

func decode(name, data string) string {
	switch name {
	case "string":
		return "String::from_utf8(" + data + ".to_vec()).map_err(|_| Error::argument(\"invalid UTF-8\"))?"
	case "bytes":
		return data + ".to_vec()"
	case "bool":
		return "match " + data + " { [0]=>false,[1]=>true,_=>return Err(Error::argument(\"invalid bool\")) }"
	case "i32", "u32", "i64", "u64", "f32", "f64":
		return name + "::from_le_bytes(" + data + ".try_into().map_err(|_| Error::argument(\"scalar length\"))?)"
	}
	if strings.HasPrefix(name, "[]") {
		element := strings.TrimPrefix(name, "[]")
		width := 8
		if strings.HasSuffix(element, "32") {
			width = 4
		}
		return fmt.Sprintf("{ if !%s.len().is_multiple_of(%d) { return Err(Error::argument(\"slice length\")); } %s.chunks_exact(%d).map(|__chunk| Ok(%s::from_le_bytes(__chunk.try_into().map_err(|_| Error::argument(\"scalar length\"))?))).collect::<Result<Vec<_>>>()? }", data, width, data, width, element)
	}
	return name + "::decode(" + data + ")?"
}

func encode(name, value string) string {
	switch name {
	case "":
		return "{ let _ = " + value + "; Vec::new() }"
	case "string":
		return value + ".into_bytes()"
	case "bytes":
		return value
	case "bool":
		return "vec![u8::from(" + value + ")]"
	case "i32", "u32", "i64", "u64", "f32", "f64":
		return value + ".to_le_bytes().to_vec()"
	}
	if strings.HasPrefix(name, "[]") {
		return value + ".iter().flat_map(|__value| __value.to_le_bytes()).collect::<Vec<u8>>()"
	}
	return value + ".encode()?"
}
