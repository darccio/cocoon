func TestPublicationFailureRestoresReplacementsAndRemovesNewFiles(t *testing.T) {
	t.Parallel()
	directory := t.TempDir()
	original := filepath.Join(directory, "original.go")
	created := filepath.Join(directory, "created.go")
	content := []byte("// Code generated by cocoon. DO NOT EDIT.\npackage original\n")
	if err := os.WriteFile(original, content, 0o640); err != nil { // #nosec G306 -- Exercise restoration of a deliberately nondefault fixture mode.
		t.Fatal(err)
	}
	// Staging the child creates a directory where the third artifact must be
	// renamed. That deterministically fails publication after two successes,
	// without racing another process or relying on filesystem permissions.
	blocked := filepath.Join(directory, "blocked")
	err := WriteSet([]Artifact{
		{Path: original, Data: []byte("replacement"), Generated: true},
		{Path: created, Data: []byte("new artifact"), Generated: true},
		{Path: blocked, Data: []byte("cannot replace a directory")},
		{Path: filepath.Join(blocked, "child"), Data: []byte("not published")},
	})
	var linkErr *os.LinkError
	if !errors.As(err, &linkErr) || linkErr.Op != "rename" {
		t.Fatalf("expected publication rename failure, got %v", err)
	}
	restored, err := os.ReadFile(original) // #nosec G304 -- Read this test's own artifact below t.TempDir.
	if err != nil || !bytes.Equal(restored, content) {
		t.Fatal("publication failure did not restore the replacement", err)
	}
	info, err := os.Stat(original)
	if err != nil || info.Mode().Perm() != 0o640 {
		t.Fatal("rollback lost the original permissions", err)
	}
	for _, path := range []string{created, filepath.Join(blocked, "child")} {
		if _, err := os.Stat(path); !errors.Is(err, os.ErrNotExist) {
			t.Fatalf("failed publication retained %s: %v", path, err)
		}
	}
	if err := filepath.WalkDir(directory, func(path string, entry fs.DirEntry, walkErr error) error {
		if walkErr != nil {
			return walkErr
		}
		if strings.HasPrefix(entry.Name(), ".cocoon-") {
			t.Errorf("publication retained staging or backup file %s", path)
		}
		return nil
	}); err != nil {
		t.Fatal(err)
	}
	if err := WriteGenerated(original, content); err != nil {
		t.Fatal("failed publication prevented retry", err)
	}
}

func TestPublicationPermissionFailures(t *testing.T) {
	t.Parallel()
	for _, scenario := range []string{"unreadable-artifact", "inaccessible-parent", "inaccessible-ancestor"} {
		t.Run(scenario, func(t *testing.T) {
			t.Parallel()
			directory := t.TempDir()
			path := filepath.Join(directory, "artifact.go")
			if err := os.WriteFile(path, []byte("Code generated\n"), 0o600); err != nil {
				t.Fatal(err)
			}
			denied := directory
			if scenario == "unreadable-artifact" {
				denied = path
			}
			if err := os.Chmod(denied, 0); err != nil {
				t.Skip("filesystem does not support permission fixtures", err)
			}
			t.Cleanup(func() {
				if err := os.Chmod(denied, 0o700); err != nil { // #nosec G302 -- Restore access to this test's owned fixture for cleanup.
					t.Error(err)
				}
			})
			if _, err := os.ReadFile(path); !errors.Is(err, os.ErrPermission) { // #nosec G304 -- Probe permissions on this test's own fixture.
				t.Skip("filesystem or process privileges do not enforce fixture permissions")
			}
			if scenario == "inaccessible-ancestor" {
				path = filepath.Join(directory, "nested", "artifact.go")
			}
			if err := WriteGenerated(path, []byte("replacement")); !errors.Is(err, os.ErrPermission) {
				t.Fatalf("publication did not retain permission error: %v", err)
			}
		})
	}
}

func TestStageFileRejectsMissingParent(t *testing.T) {
	t.Parallel()
	path := filepath.Join(t.TempDir(), "missing", "artifact")
	if name, err := stageFile(path, []byte("output"), 0o600); name != "" || !errors.Is(err, os.ErrNotExist) {
		t.Fatalf("missing staging parent: name %q, error %v", name, err)
	}
}

func TestGeneratedMarkerMustBeInHeader(t *testing.T) {
	t.Parallel()
	path := filepath.Join(t.TempDir(), "authored.go")
	authored := append(bytes.Repeat([]byte(" "), 128), []byte("Code generated\npackage authored\n")...)
	if err := os.WriteFile(path, authored, 0o600); err != nil {
		t.Fatal(err)
	}
	if err := WriteGenerated(path, []byte("replacement")); err == nil || !strings.Contains(err.Error(), "authored") {
		t.Fatal("marker outside the header authorized replacement", err)
	}
	data, err := os.ReadFile(path) // #nosec G304 -- Read this test's own authored fixture.
	if err != nil || !bytes.Equal(data, authored) {
		t.Fatal("authored file changed", err)
	}
}
